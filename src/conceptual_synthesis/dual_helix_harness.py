# ---------------------------------------------------------------------------
# State Model (Equivalent to state.py in LangGraph)
# ---------------------------------------------------------------------------

class AgentState(BaseModel):
    """
    State object passed between nodes in the Dual-Helix pipeline.
    """
    request: str = Field(..., description="The original algorithmic refactoring request.")
    vulnerabilities_identified: List[str] = Field(default_factory=list)
    implementation_plan: List[str] = Field(default_factory=list)
    linguistic_scaffold: Optional[Dict[str, Any]] = Field(default=None, description="The strict JSON API Contract.")
    synthesized_code: Optional[str] = Field(default=None, description="The Python code generated by the Coder.")
    execution_result: Optional[Dict[str, Any]] = Field(default=None, description="Result from the Sandbox Executor.")
    episodic_memory: List[str] = Field(default_factory=list, description="Verbal critiques from the Self-Reflector.")
    skill_committed: bool = Field(default=False, description="Whether the skill was committed to the library.")
    iteration_count: int = Field(default=0, description="Number of Reflexion loops executed.")

